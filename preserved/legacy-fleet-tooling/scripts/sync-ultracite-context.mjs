#!/usr/bin/env node

import { spawnSync } from 'node:child_process';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptPath = fileURLToPath(import.meta.url);
const workspaceRoot = path.resolve(path.dirname(scriptPath), '../../..');

const targets = [
  {
    frameworks: ['react', 'next', 'vitest'],
    id: 'drank',
    outputPath: 'foundry/helpers/drank/ULTRACITE.md',
  },
];

const generatedHeader = `<!--
Generated by foundry/ops/scripts/sync-ultracite-context.mjs from the pinned
Ultracite agent generator. Do not edit this file directly. The nearest
AGENTS.md remains authoritative for project commands, safety, and ownership.
-->

`;

export const renderTrackedContext = (generated) =>
  `${generatedHeader}${generated.trim()}\n`;

export const contextsMatch = (tracked, generated) =>
  tracked === renderTrackedContext(generated);

const generateContext = async (target) => {
  const stagePath = await mkdtemp(path.join(tmpdir(), `fleet-ultracite-${target.id}-`));
  const cliPath = path.join(
    workspaceRoot,
    'foundry',
    'helpers',
    'drank',
    'node_modules',
    '.bin',
    'ultracite'
  );

  try {
    await writeFile(
      path.join(stagePath, 'package.json'),
      `${JSON.stringify(
        {
          name: `fleet-ultracite-${target.id}-context`,
          packageManager: 'pnpm@10.33.2',
          private: true,
        },
        null,
        2
      )}\n`
    );

    const result = spawnSync(
      cliPath,
      [
        'init',
        '--pm',
        'pnpm',
        '--linter',
        'biome',
        '--agents',
        'universal',
        '--frameworks',
        ...target.frameworks,
        '--skip-install',
        '--quiet',
      ],
      {
        cwd: stagePath,
        encoding: 'utf8',
        env: { ...process.env, CI: '1', NO_COLOR: '1' },
      }
    );

    if (result.error) {
      throw result.error;
    }
    if (result.status !== 0) {
      throw new Error(
        `Ultracite context generation failed for ${target.id}: ${result.stderr || result.stdout}`
      );
    }

    return await readFile(path.join(stagePath, 'AGENTS.md'), 'utf8');
  } finally {
    await rm(stagePath, { force: true, recursive: true });
  }
};

const main = async () => {
  const check = process.argv.includes('--check');
  const stale = [];

  for (const target of targets) {
    const generated = await generateContext(target);
    const outputPath = path.join(workspaceRoot, target.outputPath);
    const next = renderTrackedContext(generated);

    if (check) {
      const current = await readFile(outputPath, 'utf8').catch(() => '');
      if (current !== next) {
        stale.push(target.outputPath);
      }
      continue;
    }

    await writeFile(outputPath, next);
    console.log(`Generated ${target.outputPath}`);
  }

  if (stale.length > 0) {
    console.error(`Stale Ultracite context: ${stale.join(', ')}`);
    process.exitCode = 1;
    return;
  }

  if (check) {
    console.log(`Ultracite context current (${targets.length})`);
  }
};

if (process.argv[1] && path.resolve(process.argv[1]) === scriptPath) {
  await main();
}
